/**
 * Unity 2022.3 LTS Headless Exporter & C# Synthesizer
 *
 * Compiles native C# scripts and scene definitions from Meta Muse Wonder
 * specifications into production-ready Unity projects.
 */

import fs from "node:fs";
import path from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const execFileAsync = promisify(execFile);
const UNITY_BINARY = "/opt/unity-editor/Editor/Unity";

export class UnityExporter {
  constructor(projectRoot) {
    this.projectRoot = projectRoot || "/tmp/opencode/unity_export_project";
  }

  /**
   * Generates standard Unity C# Player Controller
   */
  generatePlayerControllerCs(mechanics) {
    const speed = mechanics?.physics?.playerSpeed || 14.0;
    const jumpForce = mechanics?.physics?.jumpVelocity || 9.5;

    return `// Auto-generated by Agentic Game Studio (Meta Muse Wonder Engine)
using UnityEngine;

[RequireComponent(typeof(CharacterController))]
public class AgenticPlayerController : MonoBehaviour
{
    [Header("Movement")]
    public float moveSpeed = ${speed}f;
    public float jumpForce = ${jumpForce}f;
    public float gravity = -20.0f;

    private CharacterController controller;
    private Vector3 velocity;
    private bool isGrounded;

    void Start()
    {
        controller = GetComponent<CharacterController>();
    }

    void Update()
    {
        isGrounded = controller.isGrounded;
        if (isGrounded && velocity.y < 0)
        {
            velocity.y = -2f;
        }

        float h = Input.GetAxis("Horizontal");
        float v = Input.GetAxis("Vertical");
        Vector3 move = transform.right * h + transform.forward * v;

        controller.Move(move * moveSpeed * Time.deltaTime);

        if (Input.GetButtonDown("Jump") && isGrounded)
        {
            velocity.y = Mathf.Sqrt(jumpForce * -2f * gravity);
        }

        velocity.y += gravity * Time.deltaTime;
        controller.Move(velocity * Time.deltaTime);
    }
}
`;
  }

  /**
   * Generates standard Unity C# Game Manager
   */
  generateGameManagerCs(gameSpec) {
    const title = gameSpec?.title || "Agentic World";

    return `// Auto-generated by Agentic Game Studio (Meta Muse Wonder Engine)
using UnityEngine;

public class AgenticGameManager : MonoBehaviour
{
    public static AgenticGameManager Instance;
    public int score = 0;

    void Awake()
    {
        if (Instance == null) Instance = this;
        else Destroy(gameObject);
    }

    public void AddScore(int amount)
    {
        score += amount;
        Debug.Log("[Agentic Game Studio] Score updated: " + score);
    }
}
`;
  }

  /**
   * Writes C# assets to a Unity Project folder
   */
  exportProject(gameSpec, outDir = this.projectRoot) {
    const scriptsDir = path.join(outDir, "Assets", "Scripts");
    fs.mkdirSync(scriptsDir, { recursive: true });

    const playerCs = this.generatePlayerControllerCs(gameSpec.mechanics);
    const managerCs = this.generateGameManagerCs(gameSpec);

    fs.writeFileSync(
      path.join(scriptsDir, "AgenticPlayerController.cs"),
      playerCs,
      "utf8",
    );
    fs.writeFileSync(
      path.join(scriptsDir, "AgenticGameManager.cs"),
      managerCs,
      "utf8",
    );

    // Minimal but real Unity project skeleton: Unity Hub can open this
    // folder directly (version + package manifest are what it needs first).
    const settingsDir = path.join(outDir, "ProjectSettings");
    fs.mkdirSync(settingsDir, { recursive: true });
    fs.writeFileSync(
      path.join(settingsDir, "ProjectVersion.txt"),
      "m_EditorVersion: 2022.3.11f1\nm_EditorVersionWithRevision: 2022.3.11f1 (305b81aae6fe)\n",
      "utf8",
    );
    const packagesDir = path.join(outDir, "Packages");
    fs.mkdirSync(packagesDir, { recursive: true });
    fs.writeFileSync(
      path.join(packagesDir, "manifest.json"),
      JSON.stringify({ dependencies: {} }, null, 2),
      "utf8",
    );
    fs.writeFileSync(
      path.join(outDir, "README-Unity.txt"),
      "Open this folder in Unity 2022.3.11f1 (Unity Hub > Open). Create an empty scene, add an empty GameObject, attach AgenticPlayerController.cs (add a CharacterController when prompted) and AgenticGameManager.cs, then press Play.\n",
      "utf8",
    );

    return {
      success: true,
      path: outDir,
      scripts: ["AgenticPlayerController.cs", "AgenticGameManager.cs"],
    };
  }

  /**
   * Runs headless batchmode validation if Unity editor is available.
   * Honest result: any non-zero exit or spawn error is a failure.
   */
  async validateCompilation(projectPath = this.projectRoot) {
    if (!fs.existsSync(UNITY_BINARY)) {
      return {
        validated: false,
        reason: "Unity binary not present in environment",
      };
    }

    try {
      const args = [
        "-batchmode",
        "-nographics",
        "-quit",
        "-projectPath",
        projectPath,
        "-logFile",
        "/tmp/opencode/unity_batchmode_verify.log",
      ];
      await execFileAsync(UNITY_BINARY, args, { timeout: 120000 });
      return { validated: true };
    } catch (err) {
      return {
        validated: false,
        reason: `Unity batchmode failed (exit ${err.code ?? "unknown"})`,
      };
    }
  }
}
