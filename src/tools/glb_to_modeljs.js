#!/usr/bin/env node
/**
 * Horizon Sprint — glb_to_modeljs (VISUAL UPGRADE Step 2).
 * Generic minimal GLB -> JS geometry extractor (no external deps).
 * Reads mesh primitives with POSITION + NORMAL (+TEXCOORD_0, +indices),
 * writes base64-packed Float32/Uint arrays as `window.G.ModelData`
 * plus a `G.modelGeo(name)` THREE.BufferGeometry helper (r128-safe).
 *
 * Assumes identity node transforms (models built at origin). Materials ignored.
 * Usage: node src/tools/glb_to_modeljs.js <in.glb> <out_model_data.js>
 */
import fs from "node:fs";

const [inPath, outPath] = process.argv.slice(2);
if (!inPath || !outPath) {
  console.error("Usage: node src/tools/glb_to_modeljs.js <in.glb> <out.js>");
  process.exit(2);
}
const buf = fs.readFileSync(inPath);
if (buf.readUInt32LE(0) !== 0x46546c67) {
  console.error("Not a GLB file (bad magic)");
  process.exit(1);
}
let off = 12;
let json = null, bin = null;
while (off + 8 <= buf.length) {
  const len = buf.readUInt32LE(off);
  const type = buf.readUInt32LE(off + 4);
  const chunk = buf.subarray(off + 8, off + 8 + len);
  if (type === 0x4e4f534a) json = JSON.parse(chunk.toString("utf8"));
  if (type === 0x004e4942) bin = chunk;
  off += 8 + len;
}
if (!json || !bin) {
  console.error("GLB missing JSON or BIN chunk");
  process.exit(1);
}
const COMP = { 5120: Int8Array, 5121: Uint8Array, 5122: Int16Array, 5123: Uint16Array, 5125: Uint32Array, 5126: Float32Array };
const NCOMP = { SCALAR: 1, VEC2: 2, VEC3: 3, VEC4: 4 };
function readAcc(i) {
  const a = json.accessors[i];
  const bv = json.bufferViews[a.bufferView];
  const Arr = COMP[a.componentType];
  if (!Arr) throw new Error("unsupported componentType " + a.componentType);
  const n = NCOMP[a.type];
  const byteOff = (bv.byteOffset || 0) + (a.byteOffset || 0);
  const stride = bv.byteStride || n * Arr.BYTES_PER_ELEMENT;
  const out = new Arr(a.count * n);
  const dv = new DataView(bin.buffer, bin.byteOffset, bin.byteLength);
  for (let k = 0; k < a.count; k++) {
    for (let c = 0; c < n; c++) {
      const p = byteOff + k * stride + c * Arr.BYTES_PER_ELEMENT;
      let v;
      if (Arr === Float32Array) v = dv.getFloat32(p, true);
      else if (Arr === Uint16Array) v = dv.getUint16(p, true);
      else if (Arr === Uint32Array) v = dv.getUint32(p, true);
      else if (Arr === Uint8Array) v = dv.getUint8(p);
      else if (Arr === Int16Array) v = dv.getInt16(p, true);
      else v = dv.getInt8(p);
      out[k * n + c] = v;
    }
  }
  return out;
}
function b64(typed) {
  return Buffer.from(typed.buffer, typed.byteOffset, typed.byteLength).toString("base64");
}
const meshes = {};
for (const mesh of json.meshes || []) {
  const prim = mesh.primitives[0];
  if (!prim || prim.attributes.POSITION === undefined) continue;
  const pos = readAcc(prim.attributes.POSITION);
  const nor = prim.attributes.NORMAL !== undefined ? readAcc(prim.attributes.NORMAL) : null;
  const uv = prim.attributes.TEXCOORD_0 !== undefined ? readAcc(prim.attributes.TEXCOORD_0) : null;
  const idx = prim.indices !== undefined ? readAcc(prim.indices) : null;
  meshes[mesh.name] = {
    pos: b64(pos), nor: nor ? b64(nor) : null, uv: uv ? b64(uv) : null,
    idx: idx ? b64(idx) : null, idx32: idx instanceof Uint32Array,
    count: pos.length / 3, idxCount: idx ? idx.length : 0,
  };
  console.log(`mesh ${mesh.name}: verts=${pos.length / 3} tris=${(idx ? idx.length : pos.length / 3) / 3}`);
}
const js =
  "/* Horizon Sprint — model_data.js (generated by src/tools/glb_to_modeljs.js — do not hand-edit) */\n" +
  "(function(){\nwindow.G=window.G||{};var G=window.G;\n" +
  "G.ModelData=" + JSON.stringify(meshes) + ";\n" +
  "function dec(b64,Arr){var s=atob(b64),b=new Uint8Array(s.length);for(var i=0;i<s.length;i++)b[i]=s.charCodeAt(i);return new Arr(b.buffer);}\n" +
  "G.modelGeo=function(name){var m=G.ModelData[name];if(!m||!window.THREE)return null;\n" +
  "var g=new THREE.BufferGeometry();\n" +
  "g.setAttribute('position',new THREE.BufferAttribute(dec(m.pos,Float32Array),3));\n" +
  "if(m.nor)g.setAttribute('normal',new THREE.BufferAttribute(dec(m.nor,Float32Array),3));else g.computeVertexNormals();\n" +
  "if(m.uv)g.setAttribute('uv',new THREE.BufferAttribute(dec(m.uv,Float32Array),2));\n" +
  "if(m.idx)g.setIndex(new THREE.BufferAttribute(dec(m.idx,m.idx32?Uint32Array:Uint16Array),1));\n" +
  "return g;};\n})();\n";
fs.writeFileSync(outPath, js);
console.log("wrote " + outPath + " (" + Math.round(js.length / 1024) + " KB)");
