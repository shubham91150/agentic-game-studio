#!/usr/bin/env node
/**
 * Horizon Sprint — obj_to_modeljs (VISUAL UPGRADE Step 2).
 * Minimal Wavefront OBJ -> JS geometry extractor (no external deps).
 * Splits objects by `o`/`g` lines, dedupes v/vt/vn combos into indexed
 * BufferGeometry data, writes base64-packed arrays as `window.G.ModelData`
 * plus a `G.modelGeo(name)` THREE.BufferGeometry helper (r128-safe).
 * Usage: node src/tools/obj_to_modeljs.js <in.obj> <out_model_data.js>
 */
import fs from "node:fs";

const [inPath, outPath] = process.argv.slice(2);
if (!inPath || !outPath) {
  console.error("Usage: node src/tools/obj_to_modeljs.js <in.obj> <out.js>");
  process.exit(2);
}
const lines = fs.readFileSync(inPath, "utf8").split("\n");
const V = [], VT = [], VN = [];
const meshes = {};
let cur = null;
function use(name) {
  if (!meshes[name]) meshes[name] = { pos: [], nor: [], uv: [], idx: [], map: new Map() };
  cur = meshes[name];
}
use("default");
for (const ln of lines) {
  const p = ln.split(" ");
  if (p[0] === "v") V.push(+p[1], +p[2], +p[3]);
  else if (p[0] === "vt") VT.push(+p[1], +p[2]);
  else if (p[0] === "vn") VN.push(+p[1], +p[2], +p[3]);
  // Blender OBJ exporter compounds names as "<obj>_<data>"; normalize back.
  else if (p[0] === "o" || p[0] === "g") {
    let nm = (p[1] || "default").trim().replace(/_mesh$/, "");
    const dup = nm.match(/^(.*)_\1$/);
    if (dup) nm = dup[1];
    use(nm);
  }
  else if (p[0] === "f") {
    for (let k = 1; k < p.length; k++) {
      const key = p[k];
      let id = cur.map.get(key);
      if (id === undefined) {
        const [vi, ti, ni] = key.split("/").map(s => parseInt(s, 10));
        const v3 = (vi - 1) * 3, t2 = (ti - 1) * 2, n3 = (ni - 1) * 3;
        cur.pos.push(V[v3], V[v3 + 1], V[v3 + 2]);
        if (ti) cur.uv.push(VT[t2], VT[t2 + 1]);
        if (ni) cur.nor.push(VN[n3], VN[n3 + 1], VN[n3 + 2]);
        id = cur.map.size;
        cur.map.set(key, id);
      }
      cur.idx.push(id);
    }
  }
}
function b64(arr, Arr) {
  const t = new Arr(arr);
  return Buffer.from(t.buffer, t.byteOffset, t.byteLength).toString("base64");
}
const out = {};
for (const name of Object.keys(meshes)) {
  const m = meshes[name];
  if (!m.idx.length) continue;
  const idx32 = m.map.size > 65535;
  let mnx = 1e9, mxx = -1e9, mny = 1e9, mxy = -1e9, mnz = 1e9, mxz = -1e9;
  for (let i = 0; i < m.pos.length; i += 3) {
    mnx = Math.min(mnx, m.pos[i]); mxx = Math.max(mxx, m.pos[i]);
    mny = Math.min(mny, m.pos[i + 1]); mxy = Math.max(mxy, m.pos[i + 1]);
    mnz = Math.min(mnz, m.pos[i + 2]); mxz = Math.max(mxz, m.pos[i + 2]);
  }
  out[name] = {
    pos: b64(m.pos, Float32Array),
    nor: m.nor.length ? b64(m.nor, Float32Array) : null,
    uv: m.uv.length ? b64(m.uv, Float32Array) : null,
    idx: b64(m.idx, idx32 ? Uint32Array : Uint16Array),
    idx32, count: m.map.size, idxCount: m.idx.length,
  };
  console.log(`mesh ${name}: verts=${m.map.size} tris=${m.idx.length / 3} bbox=[${mnx.toFixed(2)},${mxx.toFixed(2)}] [${mny.toFixed(2)},${mxy.toFixed(2)}] [${mnz.toFixed(2)},${mxz.toFixed(2)}]`);
}
const js =
  "/* Horizon Sprint — model_data.js (generated by src/tools/obj_to_modeljs.js — do not hand-edit) */\n" +
  "(function(){\nwindow.G=window.G||{};var G=window.G;\n" +
  "G.ModelData=" + JSON.stringify(out) + ";\n" +
  "function dec(b64,Arr){var s=atob(b64),b=new Uint8Array(s.length);for(var i=0;i<s.length;i++)b[i]=s.charCodeAt(i);return new Arr(b.buffer);}\n" +
  "G.modelGeo=function(name){var m=G.ModelData[name];if(!m||!window.THREE)return null;\n" +
  "var g=new THREE.BufferGeometry();\n" +
  "g.setAttribute('position',new THREE.BufferAttribute(dec(m.pos,Float32Array),3));\n" +
  "if(m.nor)g.setAttribute('normal',new THREE.BufferAttribute(dec(m.nor,Float32Array),3));else g.computeVertexNormals();\n" +
  "if(m.uv)g.setAttribute('uv',new THREE.BufferAttribute(dec(m.uv,Float32Array),2));\n" +
  "if(m.idx)g.setIndex(new THREE.BufferAttribute(dec(m.idx,m.idx32?Uint32Array:Uint16Array),1));\n" +
  "return g;};\n})();\n";
fs.writeFileSync(outPath, js);
console.log("wrote " + outPath + " (" + Math.round(js.length / 1024) + " KB)");
